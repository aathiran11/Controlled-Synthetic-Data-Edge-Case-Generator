"""
Phase 2 Test Verification Script for Gemini AI Planner.
Tests E-commerce request, Logistics request, Invalid request handling,
and Pydantic JSON schema compliance.
"""

import unittest
from fastapi.testclient import TestClient
from main import app
from app.schemas.ai_plan import GenerationPlan

client = TestClient(app)

class TestPhase2AIPlanner(unittest.TestCase):

    def test_01_logistics_natural_language_request(self):
        """Test logistics prompt: 'Generate 5000 logistics records with delivery delays, vehicle types, weather conditions, and 10% rare failure cases.'"""
        prompt = "Generate 5000 logistics records with delivery delays, vehicle types, weather conditions, and 10% rare failure cases."
        payload = {
            "prompt": prompt,
            "seed": 42,
            "execute_generation": True
        }
        response = client.post("/api/ai/plan", json=payload)
        self.assertEqual(response.status_code, 200)
        data = response.json()
        
        self.assertTrue(data["success"])
        self.assertIsNotNone(data["plan"])
        
        # Verify plan is valid Pydantic GenerationPlan
        plan = GenerationPlan(**data["plan"])
        self.assertEqual(plan.domain, "logistics")
        self.assertEqual(plan.num_rows, 5000)
        self.assertAlmostEqual(plan.edge_case_config.edge_case_pct, 0.10, delta=0.01)
        self.assertGreater(len(plan.columns), 0)

        # Verify dataset execution: 5000 rows generated by Python engine
        self.assertIsNotNone(data["generated_dataset"])
        dataset = data["generated_dataset"]
        self.assertEqual(dataset["total_rows"], 5000)
        self.assertEqual(dataset["edge_case_rows_count"], 500)
        self.assertEqual(dataset["clean_rows_count"], 4500)

        print("[PASS] Logistics NL prompt converted to GenerationPlan (5000 rows, 10% edge cases).")

    def test_02_ecommerce_natural_language_request(self):
        """Test e-commerce prompt: 'Generate 2500 ecommerce order records with discount surges, payment methods, and 15% edge case anomalies.'"""
        prompt = "Generate 2500 ecommerce order records with discount surges, payment methods, and 15% edge case anomalies."
        payload = {
            "prompt": prompt,
            "seed": 99,
            "execute_generation": True
        }
        response = client.post("/api/ai/plan", json=payload)
        self.assertEqual(response.status_code, 200)
        data = response.json()
        
        self.assertTrue(data["success"])
        plan = GenerationPlan(**data["plan"])
        self.assertEqual(plan.domain, "ecommerce")
        self.assertEqual(plan.num_rows, 2500)
        self.assertAlmostEqual(plan.edge_case_config.edge_case_pct, 0.15, delta=0.01)

        dataset = data["generated_dataset"]
        self.assertEqual(dataset["total_rows"], 2500)
        self.assertEqual(dataset["edge_case_rows_count"], 375)

        print("[PASS] E-commerce NL prompt converted to GenerationPlan (2500 rows, 15% edge cases).")

    def test_03_invalid_unclear_request_handling(self):
        """Test short/invalid prompt (< 3 chars) returns 422 Unprocessable Entity"""
        payload = {"prompt": "a"}
        response = client.post("/api/ai/plan", json=payload)
        self.assertEqual(response.status_code, 422)
        print("[PASS] Invalid request handling verified (422 for short prompt).")

    def test_04_plan_only_execution_flag(self):
        """Test execute_generation=False returns plan without generating data rows"""
        prompt = "Generate 1000 finance banking fraud records with 5% risk outliers"
        payload = {
            "prompt": prompt,
            "execute_generation": False
        }
        response = client.post("/api/ai/plan", json=payload)
        self.assertEqual(response.status_code, 200)
        data = response.json()
        
        self.assertTrue(data["success"])
        self.assertIsNotNone(data["plan"])
        self.assertIsNone(data["generated_dataset"])
        print("[PASS] Plan-only execution verified (execute_generation=False returns plan only).")

if __name__ == "__main__":
    unittest.main()
