from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional
from app.schemas.dataset import ColumnSpec, EdgeCaseConfig, GenerateDatasetResponse

class GenerationPlan(BaseModel):
    domain: str = Field("custom", description="Domain: ecommerce, finance, healthcare, logistics, iot, or custom")
    num_rows: int = Field(1000, ge=1, le=50000, description="Target dataset size (1 to 50,000)")
    scenario_summary: str = Field("", description="Summary of user scenario request")
    business_rules: List[str] = Field(default_factory=list, description="Business logic rules inferred from prompt")
    columns: List[ColumnSpec] = Field(default_factory=list, description="Column definitions generated by AI planner")
    edge_case_config: EdgeCaseConfig = Field(default_factory=EdgeCaseConfig, description="Edge case configuration")

class AIPlanRequest(BaseModel):
    prompt: str = Field(..., min_length=3, description="Natural language dataset description")
    seed: Optional[int] = Field(None, description="Random seed for deterministic generation")
    execute_generation: bool = Field(True, description="If True, immediately feeds plan into Python generator")

class AIPlanResponse(BaseModel):
    success: bool
    prompt: str
    plan: Optional[GenerationPlan] = None
    generated_dataset: Optional[GenerateDatasetResponse] = None
    error_message: Optional[str] = None
